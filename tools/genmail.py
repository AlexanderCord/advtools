#!/usr/bin/env python3
"""
Generate assets/mail.js — obfuscated contact address.

Improves on the classic fragment-and-filler technique in three ways:

  1. RANDOMISED AT BUILD TIME. Every run emits different identifier names, a
     different XOR key, different chunk boundaries and different decoys. Two
     deploys share no signature, so pattern-matching the script itself fails.

  2. NOTHING IN THE DOM UNTIL A TRUSTED GESTURE. The 2007-era approach used
     document.write() at load, which means the address IS in the DOM for any
     headless browser that merely opens the page. Here it is assembled inside a
     click handler gated on event.isTrusted and never before.

  3. DECOYS THAT POISON STATIC EXTRACTION. Roughly half the stored chunks are
     never used. Concatenating every string literal in the file yields garbage.

HONEST LIMIT: none of this defeats a real browser driving the page. It defeats
regex-over-HTML harvesters, which is the overwhelming majority of them. The only
robust answer to automation is not publishing the address at all — see README.

Usage:  python3 tools/genmail.py "info@advtools.net" > assets/mail.js
"""

import random
import string
import sys


def ident(n=None):
    """A short identifier that looks like minifier output."""
    first = random.choice(string.ascii_lowercase + "_$")
    rest = "".join(random.choice(string.ascii_letters + string.digits + "_$")
                   for _ in range(n or random.randint(1, 3)))
    return first + rest


def build(address: str) -> str:
    key = [random.randint(1, 255) for _ in range(random.randint(5, 11))]

    # XOR with a rotating key, then render as hex so the payload carries no
    # characters that look like an address.
    hexed = "".join("%02x" % (ord(c) ^ key[i % len(key)])
                    for i, c in enumerate(address))

    # Split into runs of 3-7 hex chars, matching the original technique's shape.
    chunks, i = [], 0
    while i < len(hexed):
        take = random.randint(3, 7)
        chunks.append(hexed[i:i + take])
        i += take

    # Interleave decoys, then shuffle so storage order != assembly order.
    decoys = ["".join(random.choice("0123456789abcdef")
                      for _ in range(random.randint(3, 7)))
              for _ in range(len(chunks) + random.randint(2, 5))]

    table = [(c, True) for c in chunks] + [(d, False) for d in decoys]
    random.shuffle(table)

    store = [c for c, _ in table]
    # Positions of the real chunks, in assembly order.
    real_positions, cursor = [], 0
    for c in chunks:
        for idx in range(cursor, len(table)):
            if table[idx][1] and table[idx][0] == c and idx not in real_positions:
                real_positions.append(idx)
                break
        else:
            real_positions.append(next(i for i, (v, r) in enumerate(table)
                                       if r and v == c and i not in real_positions))

    v = {k: ident() for k in
         ("store", "order", "key", "decode", "out", "i", "j", "hex", "el", "ev", "addr", "n")}

    js = f"""/* generated by tools/genmail.py — do not edit by hand, regenerate instead */
(function () {{
  'use strict';
  var {v['store']} = {store!r}.map(String);
  var {v['order']} = {real_positions!r};
  var {v['key']} = {key!r};

  function {v['decode']}() {{
    var {v['hex']} = '';
    for (var {v['i']} = 0; {v['i']} < {v['order']}.length; {v['i']}++) {{
      {v['hex']} += {v['store']}[{v['order']}[{v['i']}]];
    }}
    var {v['out']} = '';
    for (var {v['j']} = 0; {v['j']} < {v['hex']}.length; {v['j']} += 2) {{
      {v['out']} += String.fromCharCode(
        parseInt({v['hex']}.substr({v['j']}, 2), 16) ^ {v['key']}[({v['j']} / 2) % {v['key']}.length]
      );
    }}
    return {v['out']};
  }}

  function {v['n']}({v['el']}) {{
    {v['el']}.addEventListener('click', function ({v['ev']}) {{
      // A synthetic click never carries isTrusted, so a scripted dispatch
      // gets nothing. Real clicks and keyboard activation both do.
      if (!{v['ev']}.isTrusted) return;
      {v['ev']}.preventDefault();
      var {v['addr']} = {v['decode']}();
      {v['el']}.textContent = {v['addr']};
      {v['el']}.setAttribute('data-revealed', '1');
      var a = document.createElement('a');
      a.href = 'ma' + 'il' + 'to' + ':' + {v['addr']};
      a.textContent = {v['addr']};
      a.className = {v['el']}.className;
      {v['el']}.parentNode.replaceChild(a, {v['el']});
    }});
  }}

  var els = document.querySelectorAll('[data-contact]');
  for (var q = 0; q < els.length; q++) {{ {v['n']}(els[q]); }}
}})();
"""
    return js


if __name__ == "__main__":
    addr = sys.argv[1] if len(sys.argv) > 1 else "info@advtools.net"
    sys.stdout.write(build(addr))
